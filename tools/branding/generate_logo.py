"""Write the game's title logo as a C header, for the launcher's header band.

    generate_logo.py --archive game_files/Data/Data_dvd.zip --header mm3_logo.h

The logo (Menu/Gfx/mm3_logo.cdds) is game artwork, so it is read from the installed game when
the launcher is built and is never committed. Without the archive or Pillow, an empty logo is
written and the launcher simply draws no picture. The pixels are premultiplied BGRA rows.
"""
import argparse
import io
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOGO = "Menu/Gfx/mm3_logo.cdds"


def load(archive: Path):
    sys.path.insert(0, str(ROOT / "tools" / "car-models"))
    import mm3_textures
    from PIL import Image
    with zipfile.ZipFile(archive) as zipped:
        dds = mm3_textures.cdds_to_dds(zipped.read(LOGO))
    return Image.open(io.BytesIO(dds)).convert("RGBA")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    args = parser.parse_args()
    width = height = 0
    data = b"\0"
    try:
        image = load(args.archive)
        width, height = image.size
        raw = image.tobytes()
        pixels = bytearray(len(raw))
        for i in range(0, len(raw), 4):
            r, g, b, a = raw[i:i + 4]
            pixels[i:i + 4] = bytes((b * a // 255, g * a // 255, r * a // 255, a))
        data = bytes(pixels)
    except (ImportError, OSError, KeyError, ValueError) as error:
        print(f"generate_logo: no logo ({type(error).__name__}: {error}); the launcher header will have none")
    lines = [f"/* Generated by tools/branding/generate_logo.py from {LOGO}. Do not edit or commit. */",
             "#ifndef MM3_LOGO_H", "#define MM3_LOGO_H",
             f"#define MM3_LOGO_WIDTH {width}", f"#define MM3_LOGO_HEIGHT {height}",
             "static const unsigned char mm3_logo_bgra[] = {"]
    for start in range(0, len(data), 24):
        lines.append(",".join(str(byte) for byte in data[start:start + 24]) + ",")
    lines += ["};", "#endif", ""]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(lines), encoding="ascii")
    print(f"generate_logo: {width}x{height} -> {args.header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
